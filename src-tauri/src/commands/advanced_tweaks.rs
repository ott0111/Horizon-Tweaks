#[command]
pub fn apply_advanced_tweak(tweak_id: String, _value: String) -> Result<TweakResult, String> {
    let tweaks = get_advanced_tweaks()?;
    let tweak = tweaks.iter().find(|t| t.id == tweak_id).ok_or("Tweak not found")?;
    
    crate::services::file_io::run_powershell(&tweak.script, &[])
        .map_err(|e| e.to_string())?;
    
    Ok(TweakResult {
        success: true,
        message: format!("Advanced tweak '{}' applied successfully", tweak.name),
    })
}

#[command]
pub fn reset_advanced_tweak(tweak_id: String) -> Result<TweakResult, String> {
    let rb_script = get_advanced_rollback_script(&tweak_id)
        .ok_or_else(|| format!("No rollback script available for tweak '{}'. Use the Rollback Manager.", tweak_id))?;
    
    crate::services::file_io::run_powershell(&rb_script, &[])
        .map_err(|e| format!("Rollback failed for '{}': {}", tweak_id, e))?;
    
    Ok(TweakResult {
        success: true,
        message: format!("Advanced tweak '{}' has been successfully reverted.", tweak_id),
    })
}
