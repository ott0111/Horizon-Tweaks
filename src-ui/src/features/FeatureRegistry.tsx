export interface FeatureDefinition {
  id: string;
  label: string;
  icon: LucideIcon;
  minTier: 'free' | 'basic' | 'pro' | 'ultimate' | 'admin';
  description: string;
  component: LazyExoticComponent<ComponentType<any>>;
  category: 'dashboard' | 'optimization' | 'analysis' | 'system' | 'admin' | 'documentation' | 'ai';
  enabled: boolean;
  standalone?: boolean;
  version: string;
  dependencies: string[];
  apiEndpoints: string[];
}

type LazyImport = () => Promise<{ default: ComponentType<any> }>;

function lazyFeature(importFn: LazyImport, name: string): LazyExoticComponent<ComponentType<any>> {
  const component = lazy(importFn) as LazyExoticComponent<ComponentType<any>> & { displayName?: string };
  component.displayName = `LazyFeature(${name})`;
  return component;
}

