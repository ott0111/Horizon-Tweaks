export function getFeaturesByTier(tier: string): FeatureDefinition[] {
  const tierOrder = ['free', 'basic', 'pro', 'ultimate', 'admin'];
  const userIdx = tierOrder.indexOf(tier);
  return FEATURE_REGISTRY.filter(f => {
    if (!f.enabled) return false;
    if (tier === 'admin') return true;
    const minIdx = tierOrder.indexOf(f.minTier);
    return userIdx >= minIdx;
  });
}

export function getFeatureById(id: string): FeatureDefinition | undefined {
  return FEATURE_REGISTRY.find(f => f.id === id);
}

export function getFeaturesByCategory(category: string): FeatureDefinition[] {
  return FEATURE_REGISTRY.filter(f => f.enabled && f.category === category);
}

export function getDisabledFeatures(tier: string): string[] {
  const tierOrder = ['free', 'basic', 'pro', 'ultimate', 'admin'];
  const userIdx = tierOrder.indexOf(tier);
  return FEATURE_REGISTRY
    .filter(f => {
      const minIdx = tierOrder.indexOf(f.minTier);
      return f.enabled && userIdx < minIdx;
    })
    .map(f => f.id);
}

export function canRunAsStandalone(featureId: string): boolean {
  const feature = getFeatureById(featureId);
  return feature?.standalone === true;
}

export function getFeatureApiEndpoints(featureId: string): string[] {
  const feature = getFeatureById(featureId);
  return feature?.apiEndpoints || [];
}

export function getStandaloneFeatures(): FeatureDefinition[] {
  return FEATURE_REGISTRY.filter(f => f.enabled && f.standalone);
}
